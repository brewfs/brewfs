//! Bounded operation labels and their indices are declared together.
macro_rules! operation_set {
    ($kind:ident, $names:ident, [$($variant:ident => $name:literal),* $(,)?]) => {
        #[derive(Clone, Copy)]
        #[repr(usize)]
        pub(crate) enum $kind { $($variant),* }
        pub(crate) const $names: &[&str] = &[$($name),*];
    };
}
